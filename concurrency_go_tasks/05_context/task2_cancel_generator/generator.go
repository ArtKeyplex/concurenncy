package generator

import "context"

// Generate возвращает канал, из которого можно читать возрастающие числа,
// начиная с нуля. Генерация прекращается при отмене ctx.

// TODO: реализовать генератор чисел с учётом отмены
func Generate(ctx context.Context) <-chan int {
	ch := make(chan int) // канал из которого будут читаться числа

	go func() {
		num := 0 // начинаем с 0

		for { // генерируем числа, пока контекст не отменён
			select { // сначала проверяем отмену контекста, чтобы при cancel() канал закрылся, а не отправилось ещё одно число
			case <-ctx.Done(): // контекст отменён
				close(ch) // закрываем канал
				return    // останавливаемся
			default: // контекст еще не отменён, идем дальше
			}
			select { // пытаемся отправить число или ждём отмену
			case <-ctx.Done(): // контекст отменён
				close(ch) // закрываем канал
				return    // и останавливаемся
			case ch <- num: // число отправлено
				num = num + 1 // увеличиваем счётчик
			}
		}
	}()
	return ch // возвращаем каналт для чтения
}
