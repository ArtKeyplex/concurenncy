// PingPong должен запускать две горутины "ping" и "pong",
// которые поочередно выводят строки пять раз каждая.
// Реализуйте синхронизацию через каналы и ожидание завершения.

// TODO: реализовать обмен сообщениями между горутинами

package main

import (
	"fmt"
	"io" // библиотека для работы с потоками ввода-вывода
	"os" // библиотека для работы с операционной системой
	"time"
)

func PingPong(w io.Writer) { // функция PingPong принимает io.Writer для вывода сообщений
	ball := make(chan struct{}) // создаём канал для передачи очереди, "мяча" между горутинами
	done := make(chan struct{}) // создаём канал для сигнала остановки

	go func() { // запускаем горутиуну для "ping"
		for i := 0; i < 5; i++ { // цикл для вывода "ping" пять раз
			<-ball                  // прочитать из канала, ожидая "мяч"
			fmt.Fprintln(w, "ping") // напечатать "ping" в поток вывода
			ball <- struct{}{}      // отправить сигнал обратно в канал, передавая "мяч" другой горутине
		}
	}()

	time.Sleep(time.Millisecond) // задержка для обеспечения правильного порядка вывода сообщений

	go func() { // запускаем горутину для "pong"
		for i := 0; i < 5; i++ { // цикл для вывода "pong" пять раз
			<-ball                  // прочитать из канала, ожидая "мяч"
			fmt.Fprintln(w, "pong") // напечатать "pong" в поток вывода

			if i < 4 { // проверяем, не достигли ли мы последнего вывода "pong"
				ball <- struct{}{} // отправляем сигнал обратно в канал, передавая "мяч" другой горутине
			}
		}

		done <- struct{}{} // отправляем сигнал завершения в канал done, чтобы уведомить основную функцию о завершении работы горутины "pong"
	}()

	ball <- struct{}{} // отправляем первый сигнал в канал ball, чтобы начать обмен сообщениями между горутинами
	<-done             // ожидаем сигнал завершения от горутины "pong" перед завершением функции
}

func main() {
	PingPong(os.Stdout) // вызываем функцию PingPong с os.Stdout для вывода сообщений в стандартный поток вывода
}
