package fibonacci

// Fib возвращает канал, из которого можно читать первые n чисел Фибоначчи.
// TODO: отправить последовательность Фибоначчи в канал

func Fib(n int) <-chan int {
	ch := make(chan int) // создаём канал
	a, b := 0, 1         // создаём две переменные: a — текущее число, b — следующее число.
	// В Фибоначчи последовательность начинается с 0 и 1.

	go func() {
		for i := 0; i < n; i++ {
			ch <- a
			a, b = b, a+b
		}
		close(ch)
	}()

	return ch
}
