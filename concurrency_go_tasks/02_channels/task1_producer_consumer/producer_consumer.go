package producerconsumer

import (
	"fmt"
	"io"
)

// Run запускает продюсера, который отправляет числа от 1 до 10, и консюмера,
// который выводит их в writer. Используйте небуферизованный канал и ожидание
// завершения горутин.

// TODO: реализовать продюсер и консюмер

func Run(w io.Writer) {
	ch := make(chan int)        // Небуферизированный канал для чисел.
	done := make(chan struct{}) // Канал для ожидания завершения консюмера.

	// Продюсер отправляет числа от 1 до 10.
	go func() {
		for i := 1; i <= 10; i++ {
			ch <- i
		}
		close(ch)
	}()

	// Консюмер выводит все полученные числа в writer.
	go func() {
		for val := range ch {
			fmt.Fprintln(w, val)
		}
		done <- struct{}{}
	}()

	// Возвращаемся только после вывода всех чисел.
	<-done
}
